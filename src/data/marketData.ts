function generateCandles(basePrice: number, points: number, volatility: number, trend: number): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let currentPrice = basePrice * (1 - (points * trend) / 2);
  const now = new Date();

  for (let i = 0; i < points; i++) {
    const timeDeltaMs = (points - 1 - i) * 3600000 * (points > 30 ? 24 : 1);
    const date = new Date(now.getTime() - timeDeltaMs);
    const timeStr = points > 30 
      ? date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
      : date.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false });

    const change = (Math.random() - 0.48 + trend) * (currentPrice * volatility);
    const open = Math.max(0.01, currentPrice);
    const close = Math.max(0.01, open + change);
    const high = Math.max(open, close) + Math.random() * (currentPrice * volatility * 0.7);
    const low = Math.min(open, close) - Math.random() * (currentPrice * volatility * 0.7);
    const volume = Math.floor(Math.random() * 500000 + 100000);

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(Math.max(0.01, low).toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }
  return candles;
}

function createSymbol(data: {
  id: string;
  symbol: string;
  name: string;
  category: MarketSymbol['category'];
  exchange: string;
  currency: string;
  price: number;
  change: number;
  changePercent: number;
  high24h: number;
  low24h: number;
  volume: string;
  marketCap?: string;
  peRatio?: number;
  dividendYield?: number;
  rating: MarketSymbol['rating'];
  logoUrl?: string;
  sector?: string;
  country?: string;
  description?: string;
}): MarketSymbol {
  const trend = data.changePercent >= 0 ? 0.003 : -0.003;
  const vol = 0.015;
  const hist1D = generateCandles(data.price, 24, vol, trend);
  const hist5D = generateCandles(data.price * 0.98, 30, vol * 1.5, trend);
  const hist1M = generateCandles(data.price * 0.95, 30, vol * 2, trend);
  const hist1Y = generateCandles(data.price * 0.85, 52, vol * 2.5, trend * 1.2);
  const hist5Y = generateCandles(data.price * 0.60, 60, vol * 3, trend * 1.5);
  
  const sparkline = hist1D.map(c => c.close);

  return {
    ...data,
    sparkline,
    historicalData: {
      '1D': hist1D,
      '5D': hist5D,
      '1M': hist1M,
      '1Y': hist1Y,
      '5Y': hist5Y,
    },
  };
}

